"""Application ports for durable institutional evidence and event ledgers."""
from __future__ import annotations

from typing import Any, Mapping, Protocol


class InstitutionalLedgerPort(Protocol):
    def append_routine_event(self, execution_id: str, event_type: str, payload: Mapping[str, Any], portfolio_id: str | None = None) -> dict[str, Any]: ...
    def list_routine_events(self) -> list[dict[str, Any]]: ...
    def save_catalyst_revision(self, catalyst: Mapping[str, Any], portfolio_id: str | None = None) -> dict[str, Any]: ...
    def list_latest_catalysts(self) -> list[dict[str, Any]]: ...
    def capture_source(self, source: Mapping[str, Any]) -> dict[str, Any]: ...
    def list_source_captures(self) -> list[dict[str, Any]]: ...
    def save_catalyst_assessment(self, assessment: Mapping[str, Any]) -> dict[str, Any]: ...
    def list_catalyst_assessments(self) -> list[dict[str, Any]]: ...
    def save_estimate_record(self, record: Mapping[str, Any]) -> dict[str, Any]: ...
    def list_estimate_records(self) -> list[dict[str, Any]]: ...
